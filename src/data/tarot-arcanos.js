// Extrae carta del día seeded por fecha de nacimiento (varía diario)
export function getCardOfDay(birthDate) {
  const today = new Date().toISOString().slice(0, 10);
  const seed = `${birthDate || 'x'}-${today}`;
  let hash = 0;
  for (const c of seed) hash = (hash * 31 + c.charCodeAt(0)) & 0xffffffff;
  return ARCANOS[Math.abs(hash) % ARCANOS.length];
}

// Tirada de 3 cartas seeded por fecha de nacimiento + día
export function getTirada(birthDate) {
  const today = new Date().toISOString().slice(0, 10);
  const used = new Set();
  const result = [];
  for (let i = 0; i < 3; i++) {
    const seed = `${birthDate || 'x'}-${today}-pos${i}`;
    let hash = 0;
    for (const c of seed) hash = (hash * 31 + c.charCodeAt(0)) & 0xffffffff;
    let idx = Math.abs(hash) % ARCANOS.length;
    while (used.has(idx)) idx = (idx + 1) % ARCANOS.length;
    used.add(idx);
    const invertido = (Math.abs(hash * 7 + i) % 3) === 0;
    result.push({ arcano: ARCANOS[idx], invertido });
  }
  return result; // [pasado, presente, futuro]
}
